#!/bin/sh
set -e

# Миграции + сид при каждом старте контейнера — seed.ts идемпотентный (безопасно
# гонять повторно), а migrate deploy сам по себе no-op, если всё уже применено.
# Нужно именно здесь (не отдельным шагом сборки), потому что на момент `docker build`
# живой БД ещё нет — она появляется только когда контейнер реально стартует.
npx prisma migrate deploy
npx tsx prisma/seed.ts

exec node server.js
